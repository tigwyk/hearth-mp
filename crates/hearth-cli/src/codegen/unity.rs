//! C# generation for the Unity typed state mirror.
//!
//! Plan v0.2b Task 5: one `HearthObject` subclass per Rust struct in a room's
//! schema, one `HearthEnum` subclass per Rust enum, and one static
//! `<Room>Intents` class with a constructor per intent variant. The classes
//! carry explicit load code against the runtime in
//! `unity/com.hearth.client/Runtime/Typed/` (no reflection, so IL2CPP stripping
//! cannot break them).
//!
//! The class name is the room name plus the Rust type name in PascalCase
//! (`TicTacToeBoard`), in `TicTacToeBoard.cs`. Properties are the PascalCase
//! wire name; a property that would hide a base member gets a trailing `_`, and
//! two wire names with the same PascalCase form are an error.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use hearth_server::SchemaDoc;
use hearth_sync::{Field, Shape, TypeDef, TypeRef, Variant, Vis};

/// First line of every C# file this generator writes.
pub const HEADER: &str =
    "// <auto-generated>generated by hearth codegen — do not edit</auto-generated>";

/// Members of `HearthNode`/`HearthEnum`/`object` a property must not hide.
const BASE_MEMBERS: &[&str] = &[
    "Load",
    "Child",
    "Equals",
    "GetHashCode",
    "ToString",
    "GetType",
    "Variant",
    "Value",
];

const HEARTH: &str = "global::Hearth";
const CONV: &str = "global::Hearth.Load.Conv";

/// Render one C# file per type, plus one intent helper per room.
pub fn generate(docs: &[SchemaDoc], namespace: &str) -> Result<Vec<(String, String)>, String> {
    let mut files = Vec::new();
    for doc in docs {
        let cx = Cx {
            room: &doc.room,
            types: &doc.types,
        };
        for (type_name, definition) in &doc.types {
            let class = class_name(&doc.room, type_name);
            let body = match definition {
                TypeDef::Struct { fields } => {
                    let hash = (doc.state == *type_name).then_some(doc.hash.as_str());
                    cx.struct_class(&class, type_name, fields, hash)?
                }
                TypeDef::Enum { variants } => cx.enum_class(&class, variants),
            };
            files.push((format!("{class}.cs"), file(namespace, &body)));
        }
        if let Some(TypeDef::Enum { variants }) = doc.types.get(&doc.intent) {
            let class = format!("{}Intents", pascal_case(&doc.room));
            files.push((
                format!("{class}.cs"),
                file(namespace, &cx.intents_class(&class, variants)),
            ));
        }
    }
    Ok(files)
}

fn file(namespace: &str, body: &str) -> String {
    format!("{HEADER}\n#nullable disable\nusing Newtonsoft.Json.Linq;\n\nnamespace {namespace}\n{{\n{body}}}\n")
}

struct Cx<'a> {
    room: &'a str,
    types: &'a BTreeMap<String, TypeDef>,
}

/// How a struct field is stored and loaded.
enum Kind {
    /// `HearthList`/`HearthMap`: a get-only property that raises its own events.
    Container,
    /// A generated struct: reloaded in place.
    Object,
    /// Everything else: assigned through `Load.Leaf` with an `On<Prop>Change` event.
    Leaf,
}

impl Cx<'_> {
    fn struct_class(
        &self,
        class: &str,
        type_name: &str,
        fields: &[Field],
        hash: Option<&str>,
    ) -> Result<String, String> {
        let props = property_names(type_name, class, fields)?;
        let mut out = String::new();
        if let Some(hash) = hash {
            writeln!(out, "    [{HEARTH}.HearthSchema(\"{hash}\")]").unwrap();
        }
        writeln!(
            out,
            "    public sealed partial class {class} : {HEARTH}.HearthObject\n    {{"
        )
        .unwrap();
        if let Some(hash) = hash {
            writeln!(
                out,
                "        public const string SchemaHash = \"{hash}\";\n"
            )
            .unwrap();
        }

        for (field, prop) in fields.iter().zip(&props) {
            if field.vis == Vis::Owner {
                out.push_str("        /// <summary>Only your own entry is visible.</summary>\n");
            }
            let ty = self.cs_type(&field.ty);
            match self.kind(&field.ty) {
                Kind::Container => {
                    writeln!(
                        out,
                        "        public {ty} {prop} {{ get; }} = {};",
                        self.new_container(&field.ty)
                    )
                    .unwrap();
                }
                Kind::Object => {
                    writeln!(out, "        public {ty} {prop} {{ get; }} = new {ty}();").unwrap();
                }
                Kind::Leaf => {
                    writeln!(out, "        public {ty} {prop} {{ get; private set; }}").unwrap();
                    writeln!(
                        out,
                        "        public event System.Action<{ty}> On{prop}Change;"
                    )
                    .unwrap();
                    writeln!(out, "        JToken __{prop};").unwrap();
                }
            }
            out.push('\n');
        }

        out.push_str("        public override void Load(JToken raw)\n        {\n");
        for (field, prop) in fields.iter().zip(&props) {
            let wire = &field.name;
            match self.kind(&field.ty) {
                Kind::Container => writeln!(out, "            {prop}.Load(raw?[\"{wire}\"]);"),
                Kind::Object => writeln!(out, "            {HEARTH}.Load.Object(raw, \"{wire}\", {prop});"),
                Kind::Leaf => writeln!(
                    out,
                    "            {prop} = {HEARTH}.Load.Leaf(raw, \"{wire}\", ref __{prop}, {prop}, {}, v => On{prop}Change?.Invoke(v));",
                    self.conv(&field.ty)
                ),
            }
            .unwrap();
        }
        out.push_str("        }\n");

        let children: Vec<_> = fields
            .iter()
            .zip(&props)
            .filter(|(field, _)| !matches!(self.kind(&field.ty), Kind::Leaf))
            .collect();
        if !children.is_empty() {
            out.push_str("\n        public override global::Hearth.HearthNode Child(string wireKey)\n        {\n            switch (wireKey)\n            {\n");
            for (field, prop) in children {
                writeln!(
                    out,
                    "                case \"{}\": return {prop};",
                    field.name
                )
                .unwrap();
            }
            out.push_str("                default: return null;\n            }\n        }\n");
        }
        out.push_str("    }\n");
        Ok(out)
    }

    fn enum_class(&self, class: &str, variants: &[Variant]) -> String {
        let mut out =
            format!("    public sealed partial class {class} : {HEARTH}.HearthEnum\n    {{\n");
        for variant in variants {
            writeln!(
                out,
                "        public const string {} = \"{}\";",
                member_name(&variant.name),
                variant.name
            )
            .unwrap();
        }
        let newtypes: Vec<_> = variants
            .iter()
            .filter_map(|v| match &v.shape {
                Shape::Newtype(ty) => Some((v, ty)),
                _ => None,
            })
            .collect();
        if !newtypes.is_empty() {
            out.push('\n');
        }
        for (variant, ty) in newtypes {
            let constant = member_name(&variant.name);
            let base = self.cs_type(ty);
            let conv = self.apply(ty, "Value");
            if is_value_type(ty) {
                writeln!(
                    out,
                    "        public {base}? As{} => Variant == {constant} ? {conv} : ({base}?)null;",
                    variant.name
                )
            } else {
                writeln!(
                    out,
                    "        public {base} As{} => Variant == {constant} ? {conv} : null;",
                    variant.name
                )
            }
            .unwrap();
        }
        out.push_str("    }\n");
        out
    }

    /// One `public static JToken <Variant>(...)` per intent, in serde's external tagging.
    fn intents_class(&self, class: &str, variants: &[Variant]) -> String {
        let mut out = format!("    public static class {class}\n    {{\n");
        for variant in variants {
            let name = &variant.name;
            let (params, value) = match &variant.shape {
                Shape::Unit => (String::new(), None),
                Shape::Newtype(ty) => (
                    format!("{} value", self.param_type(ty)),
                    Some("value".to_owned()),
                ),
                Shape::Tuple(types) => {
                    let params = types
                        .iter()
                        .enumerate()
                        .map(|(i, ty)| format!("{} value{i}", self.param_type(ty)))
                        .collect::<Vec<_>>()
                        .join(", ");
                    let items = (0..types.len())
                        .map(|i| format!("value{i}"))
                        .collect::<Vec<_>>()
                        .join(", ");
                    (params, Some(format!("new JArray({items})")))
                }
                Shape::Struct(fields) => {
                    let params = fields
                        .iter()
                        .map(|f| format!("{} {}", self.param_type(&f.ty), param_name(&f.name)))
                        .collect::<Vec<_>>()
                        .join(", ");
                    let pairs = fields
                        .iter()
                        .map(|f| format!("[\"{}\"] = {}", f.name, param_name(&f.name)))
                        .collect::<Vec<_>>()
                        .join(", ");
                    (params, Some(format!("new JObject {{ {pairs} }}")))
                }
            };
            match value {
                None => writeln!(out, "        public static JToken {name}() => \"{name}\";"),
                Some(value) => writeln!(
                    out,
                    "        public static JToken {name}({params}) => new JObject {{ [\"{name}\"] = {value} }};"
                ),
            }
            .unwrap();
        }
        out.push_str("    }\n");
        out
    }

    fn kind(&self, ty: &TypeRef) -> Kind {
        match ty {
            TypeRef::List(_) | TypeRef::Array(..) | TypeRef::Map(..) | TypeRef::SyncMap(..) => {
                Kind::Container
            }
            TypeRef::Named(name) if self.is_struct(name) => Kind::Object,
            _ => Kind::Leaf,
        }
    }

    fn is_struct(&self, name: &str) -> bool {
        matches!(self.types.get(name), Some(TypeDef::Struct { .. }))
    }

    /// The C# type of a value.
    fn cs_type(&self, ty: &TypeRef) -> String {
        match ty {
            TypeRef::Bool => "bool".into(),
            TypeRef::I8 => "sbyte".into(),
            TypeRef::I16 => "short".into(),
            TypeRef::I32 => "int".into(),
            TypeRef::I64 => "long".into(),
            TypeRef::U8 => "byte".into(),
            TypeRef::U16 => "ushort".into(),
            TypeRef::U32 => "uint".into(),
            TypeRef::U64 => "ulong".into(),
            TypeRef::F32 => "float".into(),
            TypeRef::F64 => "double".into(),
            TypeRef::String | TypeRef::PlayerId => "string".into(),
            TypeRef::Option(inner) if is_value_type(inner) => format!("{}?", self.cs_type(inner)),
            TypeRef::Option(inner) => self.cs_type(inner),
            TypeRef::List(inner) | TypeRef::Array(inner, _) => {
                format!("{HEARTH}.HearthList<{}>", self.cs_type(inner))
            }
            TypeRef::Map(_, value) | TypeRef::SyncMap(_, value) => {
                format!("{HEARTH}.HearthMap<{}>", self.cs_type(value))
            }
            TypeRef::Named(name) if self.types.contains_key(name) => class_name(self.room, name),
            TypeRef::Tuple(_) => "JArray".into(),
            TypeRef::Unit | TypeRef::Named(_) => "JToken".into(),
        }
    }

    /// A `Func<JToken, T>` expression that builds a value from its wire form.
    fn conv(&self, ty: &TypeRef) -> String {
        let leaf = |name: &str| format!("{CONV}.{name}");
        match ty {
            TypeRef::Bool => leaf("Bool"),
            TypeRef::I8 => leaf("I8"),
            TypeRef::I16 => leaf("I16"),
            TypeRef::I32 => leaf("I32"),
            TypeRef::I64 => leaf("I64"),
            TypeRef::U8 => leaf("U8"),
            TypeRef::U16 => leaf("U16"),
            TypeRef::U32 => leaf("U32"),
            TypeRef::U64 => leaf("U64"),
            TypeRef::F32 => leaf("F32"),
            TypeRef::F64 => leaf("F64"),
            TypeRef::String | TypeRef::PlayerId => leaf("Str"),
            TypeRef::Option(inner) if is_value_type(inner) => {
                format!(
                    "{CONV}.Nullable<{}>({})",
                    self.cs_type(inner),
                    self.conv(inner)
                )
            }
            TypeRef::Option(inner) => format!(
                "{CONV}.Option<{}>({})",
                self.cs_type(inner),
                self.conv(inner)
            ),
            TypeRef::List(..) | TypeRef::Array(..) | TypeRef::Map(..) | TypeRef::SyncMap(..) => {
                format!(
                    "t => {{ var n = {}; n.Load(t); return n; }}",
                    self.new_container(ty)
                )
            }
            TypeRef::Named(name) if self.types.contains_key(name) => {
                format!("{CONV}.Node<{}>", class_name(self.room, name))
            }
            TypeRef::Tuple(_) => leaf("Tuple"),
            TypeRef::Unit | TypeRef::Named(_) => "t => t".into(),
        }
    }

    /// `conv(arg)`; a lambda converter is cast first so the call parses.
    fn apply(&self, ty: &TypeRef, arg: &str) -> String {
        let conv = self.conv(ty);
        if conv.contains("=>") {
            format!(
                "((System.Func<JToken, {}>)({conv}))({arg})",
                self.cs_type(ty)
            )
        } else {
            format!("{conv}({arg})")
        }
    }

    /// `new HearthList<T>(...)` / `new HearthMap<V>(...)` for a container type.
    fn new_container(&self, ty: &TypeRef) -> String {
        match ty {
            TypeRef::List(inner) | TypeRef::Array(inner, _) => {
                format!("new {}({})", self.cs_type(ty), self.conv(inner))
            }
            TypeRef::Map(_, value) | TypeRef::SyncMap(_, value) => match &**value {
                TypeRef::Named(name) if self.is_struct(name) => {
                    let class = class_name(self.room, name);
                    format!(
                        "new {}((t, cur) => {{ var v = cur ?? new {class}(); v.Load(t); return v; }}, v => v)",
                        self.cs_type(ty)
                    )
                }
                _ => format!(
                    "new {}({HEARTH}.Load.Item<{}>({}))",
                    self.cs_type(ty),
                    self.cs_type(value),
                    self.conv(value)
                ),
            },
            _ => unreachable!("new_container is only called for containers"),
        }
    }

    /// Intent parameters: primitives keep their C# type; anything else is raw JSON.
    fn param_type(&self, ty: &TypeRef) -> String {
        match ty {
            TypeRef::Option(inner) if is_value_type(inner) => format!("{}?", self.cs_type(inner)),
            TypeRef::Option(inner) if matches!(**inner, TypeRef::String | TypeRef::PlayerId) => {
                "string".into()
            }
            t if is_value_type(t) || matches!(t, TypeRef::String | TypeRef::PlayerId) => {
                self.cs_type(t)
            }
            _ => "JToken".into(),
        }
    }
}

fn is_value_type(ty: &TypeRef) -> bool {
    matches!(
        ty,
        TypeRef::Bool
            | TypeRef::I8
            | TypeRef::I16
            | TypeRef::I32
            | TypeRef::I64
            | TypeRef::U8
            | TypeRef::U16
            | TypeRef::U32
            | TypeRef::U64
            | TypeRef::F32
            | TypeRef::F64
    )
}

/// PascalCase property names, suffixed with `_` where they would hide a base
/// member or the class name. Two wire names with one PascalCase form fail.
fn property_names(type_name: &str, class: &str, fields: &[Field]) -> Result<Vec<String>, String> {
    let mut seen: BTreeMap<String, &str> = BTreeMap::new();
    let mut out = Vec::with_capacity(fields.len());
    for field in fields {
        let pascal = pascal_case(&field.name);
        if let Some(other) = seen.insert(pascal.clone(), &field.name) {
            return Err(format!(
                "fields `{other}` and `{}` of `{type_name}` both map to C# `{pascal}`; rename one",
                field.name
            ));
        }
        out.push(if pascal == class {
            format!("{pascal}_")
        } else {
            member_name(&pascal)
        });
    }
    Ok(out)
}

fn member_name(name: &str) -> String {
    if BASE_MEMBERS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_owned()
    }
}

