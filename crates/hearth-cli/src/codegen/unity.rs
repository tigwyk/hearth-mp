/// `cell_index` -> `cellIndex`, `@`-escaped when it is a keyword.
fn param_name(name: &str) -> String {
    let pascal = pascal_case(name);
    let mut chars = pascal.chars();
    let camel = match chars.next() {
        Some(first) => first.to_lowercase().chain(chars).collect(),
        None => String::new(),
    };
    if KEYWORDS.contains(&camel.as_str()) {
        format!("@{camel}")
    } else {
        camel
    }
}

/// `TicTacToe` + `Board` -> `TicTacToeBoard`.
fn class_name(room: &str, type_name: &str) -> String {
    format!("{}{}", pascal_case(room), pascal_case(type_name))
}

/// `foo_bar` -> `FooBar`, `fooBar` -> `FooBar`.
fn pascal_case(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut capitalize = true;
    for character in name.chars() {
        if character == '_' || character == '-' {
            capitalize = true;
            continue;
        }
        if capitalize {
            out.extend(character.to_uppercase());
            capitalize = false;
        } else {
            out.push(character);
        }
    }
    out
}
