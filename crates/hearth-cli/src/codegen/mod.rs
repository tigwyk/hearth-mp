//! `hearth codegen`: export a room crate's machine-readable schema, then turn it
//! into client code.
//!
//! The export runs the room crate's own `#[cfg(test)]` schema tests (the
//! `#[hearth::room]` macro emits one per room), so a room crate needs no extra
//! binary, feature or runtime to be codegen-able.

pub mod godot;

use std::env;
use std::ffi::OsString;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use hearth_server::SchemaDoc;

/// First line of every file this tool writes. Files in the output directory that
/// start with it are ours to prune; anything else is never touched.
pub const GENERATED_HEADER: &str = "# generated by hearth codegen — do not edit";

const USAGE: &str = "usage: hearth codegen --godot <out_dir> [--manifest-path <Cargo.toml>]";

/// Run `hearth codegen ...` and return the process exit code.
pub fn run(args: &[String]) -> i32 {
    let mut out_dir: Option<PathBuf> = None;
    let mut manifest: Option<PathBuf> = None;
    let mut render_godot = false;
    let mut index = 0;
    while index < args.len() {
        match args[index].as_str() {
            "--godot" => {
                let Some(value) = args.get(index + 1) else {
                    return usage();
                };
                render_godot = true;
                out_dir = Some(PathBuf::from(value));
                index += 2;
            }
            "--manifest-path" => {
                let Some(value) = args.get(index + 1) else {
                    return usage();
                };
                manifest = Some(PathBuf::from(value));
                index += 2;
            }
            _ => return usage(),
        }
    }
    let Some(out_dir) = out_dir else {
        return usage();
    };
    if !render_godot {
        return usage();
    }
    match generate_godot(&out_dir, manifest.as_deref()) {
        Ok(()) => 0,
        Err(message) => {
            eprintln!("{message}");
            1
        }
    }
}

fn usage() -> i32 {
    eprintln!("{USAGE}");
    2
}

fn generate_godot(out_dir: &Path, manifest: Option<&Path>) -> Result<(), String> {
    let target_dir = target_directory(manifest)?;
    let schema_dir = target_dir.join("hearth-schema");
    if schema_dir.exists() {
        fs::remove_dir_all(&schema_dir)
            .map_err(|error| format!("could not clear {}: {error}", schema_dir.display()))?;
    }
    fs::create_dir_all(&schema_dir)
        .map_err(|error| format!("could not create {}: {error}", schema_dir.display()))?;

    export_schema(manifest, &schema_dir)?;
    let docs = load_docs(&schema_dir)?;
    if docs.is_empty() {
        return Err("no #[hearth::room] found in this crate".to_owned());
    }
    let files = godot::generate(&docs)?;
    write_files(out_dir, &files)
}

/// Run `cargo metadata` and take the target directory from it.
fn target_directory(manifest: Option<&Path>) -> Result<PathBuf, String> {
    let mut command = cargo_command();
    command.args(["metadata", "--format-version", "1", "--no-deps"]);
    if let Some(manifest) = manifest {
        command.arg("--manifest-path").arg(manifest);
    }
    let output = command
        .output()
        .map_err(|error| format!("could not run `cargo metadata`: {error}"))?;
    if !output.status.success() {
        return Err(format!(
            "`cargo metadata` failed:\n{}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    let metadata: serde_json::Value = serde_json::from_slice(&output.stdout)
        .map_err(|error| format!("could not parse `cargo metadata` output: {error}"))?;
    let target = metadata
        .get("target_directory")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| "`cargo metadata` did not report a target_directory".to_owned())?;
    Ok(PathBuf::from(target))
}

/// Run the crate's exported schema tests, writing their JSON into `schema_dir`.
fn export_schema(manifest: Option<&Path>, schema_dir: &Path) -> Result<(), String> {
    let mut command = cargo_command();
    command.arg("test").arg("--lib");
    if let Some(manifest) = manifest {
        command.arg("--manifest-path").arg(manifest);
    }
    command
        .arg("__hearth_schema_export")
        .env("HEARTH_SCHEMA_OUT", schema_dir);
    let output = command
        .output()
        .map_err(|error| format!("could not run `cargo test`: {error}"))?;
    if !output.status.success() {
        return Err(format!(
            "`cargo test --lib __hearth_schema_export` failed:\n{}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Ok(())
}

/// Read every `*.json` [`SchemaDoc`] in `dir`, ordered by file name.
pub fn load_docs(dir: &Path) -> Result<Vec<SchemaDoc>, String> {
    let entries = fs::read_dir(dir)
        .map_err(|error| format!("could not read {}: {error}", dir.display()))?;
    let mut paths = Vec::new();
    for entry in entries {
        let entry =
            entry.map_err(|error| format!("could not read {}: {error}", dir.display()))?;
        let path = entry.path();
        if path.is_file()
            && path
                .extension()
                .is_some_and(|extension| extension.eq_ignore_ascii_case("json"))
        {
            paths.push(path);
        }
    }
    paths.sort();
    let mut docs = Vec::with_capacity(paths.len());
    for path in paths {
        let text = fs::read_to_string(&path)
            .map_err(|error| format!("could not read {}: {error}", path.display()))?;
        let doc = serde_json::from_str(&text)
            .map_err(|error| format!("could not parse {}: {error}", path.display()))?;
        docs.push(doc);
    }
    Ok(docs)
}

/// Write generated files, then prune only our own stale output.
fn write_files(out_dir: &Path, files: &[(String, String)]) -> Result<(), String> {
    fs::create_dir_all(out_dir)
        .map_err(|error| format!("could not create {}: {error}", out_dir.display()))?;
    let mut written = Vec::with_capacity(files.len());
    for (name, contents) in files {
        let path = out_dir.join(name);
        fs::write(&path, contents)
            .map_err(|error| format!("could not write {}: {error}", path.display()))?;
        written.push(name.as_str());
    }
    for entry in fs::read_dir(out_dir)
        .map_err(|error| format!("could not read {}: {error}", out_dir.display()))?
    {
        let entry =
            entry.map_err(|error| format!("could not read {}: {error}", out_dir.display()))?;
        let path = entry.path();
        if !path.is_file() {
            continue;
        }
        let Some(name) = entry.file_name().to_str().map(str::to_owned) else {
            continue;
        };
        if written.contains(&name.as_str()) {
            continue;
        }
        // Only files carrying our header are ours to delete.
        let Ok(contents) = fs::read(&path) else {
            continue;
        };
        if contents.starts_with(GENERATED_HEADER.as_bytes()) {
            fs::remove_file(&path)
                .map_err(|error| format!("could not remove {}: {error}", path.display()))?;
        }
    }
    Ok(())
}

/// The cargo that invoked this binary (falling back to `cargo` on `PATH`).
fn cargo_command() -> Command {
    Command::new(env::var_os("CARGO").unwrap_or_else(|| OsString::from("cargo")))
}
