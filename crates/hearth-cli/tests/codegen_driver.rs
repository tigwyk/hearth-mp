//! Plan v0.2a Task 5: the `hearth codegen` driver.
//!
//! The driver shells out to `cargo test --lib __hearth_schema_export`, so this
//! test runs a real nested cargo build. It points the nested build at its own
//! `CARGO_TARGET_DIR` (`target/hearth-codegen-driver`) so it can never contend
//! for the target-dir lock with the outer `cargo test` process; that directory
//! is a normal cache inside the workspace target tree and is reused across runs.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicU32, Ordering};

const HEARTH: &str = env!("CARGO_BIN_EXE_hearth");
const HEADER: &str = "# generated by hearth codegen — do not edit";

struct TempDir(PathBuf);

impl TempDir {
    fn new(label: &str) -> Self {
        static NEXT: AtomicU32 = AtomicU32::new(0);
        let path = std::env::temp_dir().join(format!(
            "hearth-codegen-{label}-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir_all(&path).unwrap();
        Self(path)
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crates/hearth-cli is two levels below the repo root")
        .to_path_buf()
}

fn run_codegen(manifest: &Path, out_dir: &Path) -> Output {
    let target_dir = repo_root().join("target").join("hearth-codegen-driver");
    Command::new(HEARTH)
        .arg("codegen")
        .arg("--godot")
        .arg(out_dir)
        .arg("--manifest-path")
        .arg(manifest)
        .env("CARGO_TARGET_DIR", &target_dir)
        .output()
        .expect("the hearth binary runs")
}

#[test]
fn codegen_driver() {
    let repo = repo_root();

    // 1. A room crate generates files, prunes its own stale output, and never
    // touches hand-written files.
    let temp = TempDir::new("room");
    let out_dir = temp.path().join("gd");
    fs::create_dir_all(&out_dir).unwrap();
    let keep = "extends Node\n# hand written\n";
    fs::write(out_dir.join("keep.gd"), keep).unwrap();
    fs::write(out_dir.join("old.gd"), format!("{HEADER}\nstale\n")).unwrap();
    let manifest = repo
        .join("examples")
        .join("tictactoe")
        .join("Cargo.toml");

    let output = run_codegen(&manifest, &out_dir);
    assert!(
        output.status.success(),
        "codegen failed\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(
        out_dir.join("tic_tac_toe_board.gd").is_file(),
        "the stub's generated file exists: {:?}",
        fs::read_dir(&out_dir)
            .map(|entries| entries
                .filter_map(Result::ok)
                .map(|entry| entry.file_name())
                .collect::<Vec<_>>())
            .unwrap_or_default()
    );
    assert_eq!(
        fs::read_to_string(out_dir.join("keep.gd")).unwrap(),
        keep,
        "hand-written files are never touched"
    );
    assert!(
        !out_dir.join("old.gd").exists(),
        "stale files that carry the generated header are pruned"
    );

    // 2. A crate with no room fails with the documented message.
    let no_room_temp = TempDir::new("no-room");
    let no_room_out = no_room_temp.path().join("gd");
    let no_room_manifest = repo.join("crates").join("hearth-cli").join("Cargo.toml");
    let output = run_codegen(&no_room_manifest, &no_room_out);
    assert!(
        !output.status.success(),
        "codegen on a crate without a room must fail"
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("no #[hearth::room] found in this crate"),
        "stderr was: {stderr}"
    );
}
